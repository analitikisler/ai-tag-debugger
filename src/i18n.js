export const LANGUAGES = { en, tr };

export function messages(lang = "en") {
  const m = LANGUAGES[lang];
  if (!m) throw new Error(`Unsupported language "${lang}". Use: ${Object.keys(LANGUAGES).join(", ")}`);
  return m;
}
